const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('api', {
  windowControl: (action) => ipcRenderer.send('window:control', action),
  getVersion: () => ipcRenderer.invoke('app:version'),
  openStore: () => ipcRenderer.invoke('app:openStore'),
  getData: () => ipcRenderer.invoke('data:get'),
  saveData: (data) => ipcRenderer.invoke('data:save', data),
  listDisplays: () => ipcRenderer.invoke('displays:list'),
  startScreens: (url, opts) => ipcRenderer.invoke('screens:start', url, opts),
  closeAllScreens: () => ipcRenderer.invoke('screens:closeAll'),
  listScreens: () => ipcRenderer.invoke('screens:list'),
  reloadAll: (targets) => ipcRenderer.invoke('screens:reloadAll', targets),
  setupPix: (targets, opts) => ipcRenderer.invoke('pix:setup', targets, opts),
  withdrawAll: (targets) => ipcRenderer.invoke('pix:withdraw', targets),
  goHome: (targets) => ipcRenderer.invoke('screens:home', targets),
  gotoSitePage: (targets, key) => ipcRenderer.invoke('screens:goto', targets, key),
  searchSlot: (targets, query) => ipcRenderer.invoke('screens:slot', targets, query),
  openLog: () => ipcRenderer.invoke('log:open'),
  openAccount: (id) => ipcRenderer.invoke('accounts:open', id),
  closeAccount: (id) => ipcRenderer.invoke('accounts:close', id),
  listRunningAccounts: () => ipcRenderer.invoke('accounts:running'),
  onAccountsRunning: (cb) => ipcRenderer.on('accounts:running', (_e, ids) => cb(ids)),
  rotateScreen: (number) => ipcRenderer.invoke('screen:rotate', number),
  reloadScreen: (number) => ipcRenderer.invoke('screen:reload', number),
  focusScreen: (number) => ipcRenderer.invoke('screen:focus', number),
  setControl: (control) => ipcRenderer.invoke('control:set', control),
  toggleProxyScoped: (targets) => ipcRenderer.invoke('proxy:toggleScoped', targets),
  toggleBotScoped: (targets) => ipcRenderer.invoke('bot:toggleScoped', targets),
  botState: (targets) => ipcRenderer.invoke('bot:state', targets),
  toggleMute: () => ipcRenderer.invoke('audio:toggleMute'),
  muteState: () => ipcRenderer.invoke('audio:state'),
  onLog: (cb) => ipcRenderer.on('log', (_e, msg) => cb(msg)),
  onScreens: (cb) => ipcRenderer.on('screens:update', (_e, list) => cb(list)),
  onHotkey: (cb) => ipcRenderer.on('hotkey', (_e, key) => cb(key)),
  onCompact: (cb) => ipcRenderer.on('window:compact', (_e, on) => cb(Boolean(on))),
  onCompactPin: (cb) => ipcRenderer.on('window:compact-pin', (_e, pinned) => cb(Boolean(pinned))),
  listAccounts: () => ipcRenderer.invoke('accounts:list'),
  saveAccounts: (list) => ipcRenderer.invoke('accounts:save', list),
  backupAccounts: () => ipcRenderer.invoke('accounts:backup'),
  onAccounts: (cb) => ipcRenderer.on('accounts:update', (_e, list) => cb(list)),
  license: {
    state: () => ipcRenderer.invoke('license:state'),
    refresh: () => ipcRenderer.invoke('license:refresh'),
    login: (payload) => ipcRenderer.invoke('license:login', payload),
    register: (payload) => ipcRenderer.invoke('license:register', payload),
    logout: () => ipcRenderer.invoke('license:logout'),
    redeem: (key) => ipcRenderer.invoke('license:redeem', { key }),
    support: () => ipcRenderer.invoke('license:support'),
    audit: (action, details) => ipcRenderer.invoke('license:audit', action, details),
    onUpdate: (cb) => ipcRenderer.on('license:update', (_e, state) => cb(state)),
  },
})
